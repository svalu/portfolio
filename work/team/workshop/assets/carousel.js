/* Mouse dragging shares the native touch/keyboard scroll surface. */
(() => {
  const track = document.getElementById('cars');
  if (!track) return;
  let drag = null, suppressClick = false;
  const step = direction => {
    const card = track.querySelector('.car');
    if (!card) return;
    track.scrollBy({left: direction * (card.getBoundingClientRect().width + 14), behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'instant' : 'smooth'});
  };
  document.getElementById('carsPrev').onclick = () => step(-1);
  document.getElementById('carsNext').onclick = () => step(1);
  track.addEventListener('keydown', e => {
    if (e.target !== track || !['ArrowLeft','ArrowRight'].includes(e.key)) return;
    e.preventDefault(); step(e.key === 'ArrowRight' ? 1 : -1);
  });
  track.addEventListener('pointerdown', e => {
    if (e.pointerType !== 'mouse' || e.button !== 0 || track.scrollWidth <= track.clientWidth) return;
    suppressClick = false;
    drag = {id:e.pointerId, x:e.clientX, left:track.scrollLeft, moving:false};
  });
  window.addEventListener('pointermove', e => {
    if (!drag || e.pointerId !== drag.id) return;
    const dx = e.clientX - drag.x;
    if (!drag.moving && Math.abs(dx) < 6) return;
    if (!drag.moving) {
      drag.moving = true; track.classList.add('dragging');
      track.setPointerCapture(e.pointerId);
    }
    e.preventDefault(); track.scrollLeft = drag.left - dx;
  }, {passive:false});
  function end(e) {
    if (!drag || e.pointerId !== drag.id) return;
    const moved = drag.moving; drag = null;
    suppressClick = moved;
    track.classList.remove('dragging');
    if (track.hasPointerCapture(e.pointerId)) track.releasePointerCapture(e.pointerId);
    // Suppress only the click generated by releasing this drag.
    if (moved) setTimeout(() => { suppressClick = false; }, 0);
  }
  window.addEventListener('pointerup', end);
  window.addEventListener('pointercancel', end);
  track.addEventListener('lostpointercapture', end);
  track.addEventListener('click', e => {
    if (!suppressClick) return;
    suppressClick = false; e.preventDefault(); e.stopImmediatePropagation();
  }, true);
  track.addEventListener('dragstart', e => e.preventDefault());
})();
